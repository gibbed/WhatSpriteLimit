internal static unsafe class MidHook
{
    [StructLayout(LayoutKind.Sequential)]
    public struct Context
    {
        public ulong rax, rcx, rdx, rbx, rsp, rbp, rsi, rdi;
        public ulong r8, r9, r10, r11, r12, r13, r14, r15;
        public ulong rflags;
        public ulong rip;
    }

    public static IAsmHook Create(
        IReloadedHooks hooks,
        nuint site,
        int stolenLength,
        delegate* unmanaged<Context*, void> handler)
    {
        AsmHookOptions options = new()
        {
            Behaviour = AsmHookBehaviour.ExecuteFirst,
            PreferRelativeJump = true,
            MaxOpcodeSize = 5,
            hookLength = stolenLength,
        };
        return hooks.CreateAsmHook(BuildStub((ulong)handler), (long)site, options);
    }

    public static byte[] BuildStub(ulong handler)
    {
        Assembler a = new(64);

        var noRedirect = a.CreateLabel();

        AssemblerRegisterXMM[] xmm =
        {
            xmm0, xmm1, xmm2, xmm3, xmm4, xmm5, xmm6, xmm7,
            xmm8, xmm9, xmm10, xmm11, xmm12, xmm13, xmm14, xmm15,
        };

        a.push(0); // rip
        a.pushfq(); // rflags
        a.push(r15); a.push(r14); a.push(r13); a.push(r12);
        a.push(r11); a.push(r10); a.push(r9); a.push(r8);
        a.push(rdi); a.push(rsi); a.push(rbp); a.push(rsp);
        a.push(rbx); a.push(rdx); a.push(rcx); a.push(rax);
        a.add(__qword_ptr[rsp + 0x20], 13 * 8); // rsp = value at the hook site
        a.cld();

        a.mov(rbx, rsp); // rbx = Context*
        a.sub(rsp, 0x100);
        for (int i = 0; i < 16; i++)
        {
            a.movdqu(__xmmword_ptr[rsp + i * 16], xmm[i]);
        }

        a.mov(rbp, rsp);
        a.and(rsp, -16);
        a.sub(rsp, 0x20); // shadow space
        a.mov(rcx, rbx);
        a.mov(rdi, rbx); // also SysV arg 0, for the Linux stub test
        a.mov(rax, handler);
        a.call(rax);
        a.mov(rsp, rbp);
        for (int i = 0; i < 16; i++)
        {
            a.movdqu(xmm[i], __xmmword_ptr[rsp + i * 16]);
        }

        a.mov(rsp, rbx);
        a.pop(rax); a.pop(rcx); a.pop(rdx); a.pop(rbx);
        a.lea(rsp, __[rsp + 8]); // skip rsp
        a.pop(rbp); a.pop(rsi); a.pop(rdi);
        a.pop(r8); a.pop(r9); a.pop(r10); a.pop(r11);
        a.pop(r12); a.pop(r13); a.pop(r14); a.pop(r15);
        a.cmp(__qword_ptr[rsp + 8], 0);
        a.je(noRedirect);
        a.popfq();
        a.ret(); // pops rip: resume at the handler's address
        a.Label(ref noRedirect);
        a.popfq();
        a.lea(rsp, __[rsp + 8]); // drop rip; original code follows

        using MemoryStream ms = new();
        a.Assemble(new StreamCodeWriter(ms), 0u);
        return ms.ToArray();
    }
}
